import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

/**
 * Tiny "tone" previews for project media: each image is reduced to a 4×4 PNG and inlined as a data URI
 * (~100–150 bytes). Stretched under the loading grid, the browser's smooth upscaling turns it into a
 * soft blurred preview of the image's colours — no extra request, no CSS blur filter.
 *
 * Writes `content/projects/media-tones.ts`, keyed by public path (`/projects/<slug>/<file>`).
 * Run after `pnpm generate:project-media` (or whenever files under public/projects change).
 */
const rootDir = process.cwd();
const publicDir = path.join(rootDir, "public");
const projectsDir = path.join(publicDir, "projects");
const outputPath = path.join(rootDir, "content/projects/media-tones.ts");
const TONE_SIZE = 4;
const IMAGE_EXTENSIONS = new Set([".png", ".jpg", ".jpeg", ".webp", ".avif"]);

async function listImages(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return listImages(full);
      return IMAGE_EXTENSIONS.has(path.extname(entry.name).toLowerCase()) ? [full] : [];
    }),
  );
  return nested.flat();
}

/** Keep only the chunks a browser needs (IHDR, IDAT, IEND); sharp adds pHYs, which is a third of the bytes here. */
function stripPng(buffer) {
  const keep = new Set(["IHDR", "IDAT", "IEND"]);
  const parts = [buffer.subarray(0, 8)];
  let offset = 8;
  while (offset < buffer.length) {
    const length = buffer.readUInt32BE(offset);
    const type = buffer.toString("ascii", offset + 4, offset + 8);
    const end = offset + 12 + length;
    if (keep.has(type)) parts.push(buffer.subarray(offset, end));
    offset = end;
  }
  return Buffer.concat(parts);
}

async function toneFor(file) {
  const png = await sharp(file, { limitInputPixels: false })
    .rotate()
    .resize(TONE_SIZE, TONE_SIZE, { fit: "fill", kernel: "cubic" })
    .removeAlpha()
    .png({ compressionLevel: 9, palette: false })
    .toBuffer();
  return `data:image/png;base64,${stripPng(png).toString("base64")}`;
}

const files = (await listImages(projectsDir)).sort();
const tones = {};
for (const file of files) {
  const publicPath = `/${path.relative(publicDir, file).split(path.sep).join("/")}`;
  tones[publicPath] = await toneFor(file);
}

const body = `// Generated by scripts/generate-media-tones.mjs — do not edit by hand.
/** 4×4 PNG previews of project media, keyed by public path; stretched under the loading grid. */
export const projectMediaTones: Record<string, string> = ${JSON.stringify(tones, null, 2)};
`;
await fs.writeFile(outputPath, body);
console.log(`Wrote ${Object.keys(tones).length} media tones to ${path.relative(rootDir, outputPath)}`);
